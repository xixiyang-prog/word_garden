const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require('playwright');
(async () => {
  const browser = await chromium.launch({headless:true,executablePath:process.env.BROWSER_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const context = await browser.newContext({viewport:{width:1440,height:1050},acceptDownloads:true});
  const errors=[];
  context.on('page', p => p.on('pageerror', e => errors.push(e.message)));
  const page=await context.newPage();
  const root=path.resolve(__dirname,'..'), url=pathToFileURL(path.join(root,'index.html')).href;
  const key='word-garden:v1';
  const openSettings=async()=>{await page.locator('nav [href="#words"]').click();await page.locator('[data-action="worksheet"]').click();};
  const generate=async()=>{const opened=page.waitForEvent('popup');await page.locator('#worksheet-generate').click();const p=await opened;await p.waitForLoadState();return p;};
  try {
    await page.goto(url);
    await openSettings();
    assert.equal(await page.locator('#worksheet-dialog').isVisible(),true);
    assert.ok((await page.locator('#worksheet-count').textContent()).includes('12'));
    const before=await page.evaluate(k=>localStorage.getItem(k),key);
    const correction=await generate();
    assert.equal(await correction.locator('.student-sheet').count(),2);
    assert.equal(await correction.locator('.question').count(),12);
    assert.equal(await correction.locator('.answer-item').count(),12);
    assert.equal(await correction.locator('.student-sheet .answer-hint').count(),0);
    assert.equal(await correction.locator('.write-line').count(),12);
    assert.ok(!(await correction.locator('.student-sheet').allTextContents()).join('').includes('继续努力'));
    await correction.screenshot({path:path.join(root,'preview-worksheet.png'),fullPage:true});
    assert.equal(await page.evaluate(k=>localStorage.getItem(k),key),before);
    await correction.emulateMedia({media:'print'});
    assert.equal(await correction.locator('.toolbar').isVisible(),false);
    const pdf=await correction.pdf({path:path.join(root,'worksheet-sample.pdf'),preferCSSPageSize:true});
    const pages=(pdf.toString('latin1').match(/\/Type\s*\/Page\b/g)||[]).length;
    assert.ok(pages>=3 && pages<=5,'unexpected PDF page count '+pages);
    await correction.emulateMedia({media:'screen'});
    const downloading=correction.waitForEvent('download');
    await correction.locator('#download-sheet').click();
    const download=await downloading;
    const exported=await fs.readFile(await download.path(),'utf8');
    assert.ok(exported.includes('<!doctype html>'));
    assert.ok(exported.includes('参考答案'));
    assert.ok(!exported.includes('src="worksheet.js"'));
    const standalone=await context.newPage();
    const savedHTML=path.join(root,'worksheet-sample.html');
    await download.saveAs(savedHTML);
    await standalone.goto(pathToFileURL(savedHTML).href);
    assert.equal(await standalone.locator('.question').count(),12);
    assert.equal(await standalone.locator('#print-sheet').count(),1);
    await standalone.close();await correction.close();
    console.log('PASS: correction worksheet, answer separation, PDF, offline HTML, unchanged progress');

    const words=Array.from({length:17},(_,i)=>({id:'word-'+i,correct:'正确词语'+i,wrong:'错写词语'+i,hint:'提示'+i,attempts:i<2?3:0,hits:i===0?3:0,streak:i===0?3:0,errors:i===1?3:0,lastSeen:0}));
    await page.evaluate(({key,words})=>localStorage.setItem(key,JSON.stringify({version:1,words,history:[]})),{key,words});
    await page.goto(url);
    await page.locator('nav [href="#words"]').click();
    await page.locator('#word-search').fill('正确词语16');
    await page.locator('[data-action="worksheet"]').click();
    assert.ok((await page.locator('#worksheet-count').textContent()).includes('符合条件 1 组'));
    await page.locator('#worksheet-scope').selectOption('pending');
    assert.ok((await page.locator('#worksheet-count').textContent()).includes('符合条件 16 组'));
    await page.locator('#worksheet-scope').selectOption('errors');
    assert.ok((await page.locator('#worksheet-count').textContent()).includes('符合条件 1 组'));
    await page.locator('#worksheet-scope').selectOption('all');
    await page.locator('#worksheet-limit').selectOption('10');
    await page.locator('#worksheet-format').selectOption('choice');
    await page.locator('#worksheet-random').uncheck();
    const choice=await generate();
    assert.equal(await choice.locator('.question').count(),10);
    const prompts=await choice.locator('.choices').allTextContents();
    const answers=await choice.locator('.answer-item strong').allTextContents();
    answers.forEach((answer,i)=>{const letter=answer.match(/\.\s([AB])/)[1];const correct=words[i].correct;assert.ok(prompts[i].includes(letter+'. '+correct));});
    assert.equal(await choice.locator('.student-sheet').count(),2);
    await choice.close();
    console.log('PASS: search and mastery/error scopes, question limits, matching choice answer key');

    await openSettings();
    await page.locator('#worksheet-format').selectOption('correction');
    await page.locator('#worksheet-limit').selectOption('all');
    await page.locator('#worksheet-answers').uncheck();
    assert.equal(await page.locator('#worksheet-hints').isDisabled(),true);
    const studentOnly=await generate();
    assert.equal(await studentOnly.locator('.question').count(),17);
    assert.equal(await studentOnly.locator('.answers').count(),0);
    const studentHTML=await studentOnly.content();
    for(const word of words) assert.ok(!studentHTML.includes(word.correct));
    const onlyPDF=await studentOnly.pdf({preferCSSPageSize:true});
    assert.equal((onlyPDF.toString('latin1').match(/\/Type\s*\/Page\b/g)||[]).length,3);
    await studentOnly.close();
    console.log('PASS: student-only HTML contains no correct answers, 17 questions = 3 A4 pages');

    await page.evaluate(k=>localStorage.setItem(k,JSON.stringify({version:1,words:[],history:[]})),key);
    await page.goto(url);await openSettings();
    assert.equal(await page.locator('#worksheet-generate').isDisabled(),true);
    await page.locator('[data-close="worksheet-dialog"]').first().click();
    const special={...words[0],id:'safe',correct:'<img src=x onerror=alert(1)>',wrong:'</script><script>alert(1)</script>',hint:'<svg onload=alert(1)>'};
    await page.evaluate(({key,special})=>localStorage.setItem(key,JSON.stringify({version:1,words:[{...special,wrong:'错写词语'}],history:[]})),{key,special});
    await page.goto(url);await openSettings();
    await page.locator('#worksheet-answers').check();
    await page.locator('#worksheet-title').fill('<img src=x onerror=alert(1)>');
    const escaped=await generate();
    assert.equal(await escaped.locator('img,svg').count(),0);
    assert.equal(await escaped.title(),'<img src=x onerror=alert(1)>');
    await escaped.close();
    await page.setViewportSize({width:390,height:844});await openSettings();
    assert.ok(await page.locator('#worksheet-dialog').evaluate(el=>el.getBoundingClientRect().width<window.innerWidth));
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.locator('[data-close="worksheet-dialog"]').first().click();
    const original=await page.evaluate(()=>{window.originalOpen=window.open;window.open=()=>null;return true;});
    await openSettings();await page.locator('#worksheet-generate').click();
    assert.ok((await page.locator('#worksheet-error').textContent()).includes('拦截'));
    assert.equal(await page.locator('#worksheet-dialog').isVisible(),true);
    await page.evaluate(()=>{window.open=window.originalOpen;});
    assert.deepEqual(errors,[]);
    console.log('PASS: empty scopes, escaped content, mobile dialog, blocked popup feedback');
    console.log('ALL WORKSHEET TESTS PASSED.');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});

